const PROMPTS: Record<AnalyzeMode, string> = {
  describe: PROMPT_DESCRIBE,
  ocr: PROMPT_OCR,
  // 对话模式不走这段 prompt —— 它把完整多轮历史交给模型，由用户逐句驱动。
  // 这里放一段系统级的背景说明，作为对话首条消息的前缀上下文。
  chat:
    "你是一个看图助手，用户正在查看一张图片，图片会随消息附上。" +
    "请基于这张图回答用户的问题；如果用户描述了想做的修改，" +
    "请给出具体、可直接执行的修改描述（主体/颜色/风格/范围），" +
    "因为这份描述将被用于图像编辑。",
};

export function buildPrompt(mode: AnalyzeMode): string {
  return PROMPTS[mode] ?? PROMPTS.describe;
}

/** 对话模式的系统上下文：作为首条用户消息的前缀，让模型始终带着「看图」的立场。 */
export const CHAT_SYSTEM_PREFIX = PROMPTS.chat;

/**
 * 纯文本化：把 Markdown 排版符号去掉，便于粘贴进 Word / 微信 / 表格这类目标。
 * 「保留排版」和「粘到不支持排版的地方」是两个真实需求，所以复制按钮给两个口径。
 */
export function toPlainText(md: string): string {
  return md
    // 代码围栏
    .replace(/```[^\n]*\n?/g, "")
    // 表格分隔行 |---|---|
    .replace(/^\s*\|?[\s:|-]{3,}\|?\s*$/gm, "")
    // 表格竖线 → 制表符（贴进 Excel/Word 表格仍能分列）
    .replace(/^\s*\|(.+)\|\s*$/gm, (_m, inner: string) =>
      inner
        .split("|")
        .map((c) => c.trim())
        .join("\t")
    )
    // 标题符号
    .replace(/^\s{0,3}#{1,6}\s+/gm, "")
    // 引用
    .replace(/^\s{0,3}>\s?/gm, "")
    // 加粗/斜体/行内代码
    .replace(/\*\*([^*]+)\*\*/g, "$1")
    .replace(/(^|[^*])\*([^*\n]+)\*/g, "$1$2")
    .replace(/`([^`]+)`/g, "$1")
    // 列表符号（保留缩进层级）
    .replace(/^(\s*)[-*+]\s+/gm, "$1")
    // 连续空行压成一行
    .replace(/\n{3,}/g, "\n\n")
    .trim();
}
